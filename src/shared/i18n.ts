/**
 * One string in one language, with `{name}` placeholders filled in. An unknown
 * language falls back to English rather than showing the key — a missing
 * translation should read oddly, never break the screen.
 */
export function t(locale: LanguageCode, key: StringKey, vars?: Vars): string {
  const text = (STRINGS[locale] ?? STRINGS.en)[key] ?? STRINGS.en[key];
  return vars
    ? text.replace(/\{(\w+)\}/g, (whole, name: string) => String(vars[name] ?? whole))
    : text;
}
